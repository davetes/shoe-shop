const LanguageContext = createContext({ language: 'en', setLanguage: () => {}, t: (text) => text });

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState('en');
  const [ready, setReady] = useState(false);
  useEffect(() => {
    const savedLanguage = window.localStorage.getItem('shoe-shop-language');
    if (savedLanguage === 'am' || savedLanguage === 'en') setLanguage(savedLanguage);
    setReady(true);
  }, []);
  useEffect(() => {
    if (!ready) return;
    document.documentElement.lang = language;
    window.localStorage.setItem('shoe-shop-language', language);
  }, [language, ready]);
  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (text) => language === 'am' ? translations[text] || text : text
  }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}
